/**
 * Helper to generate Word-compatible HTML with clean typography,
 * single-row options, grid answer key, and detailed explanations.
 */
function generateAndDownloadWordFile(rawText: string, title: string, fileName: string) {
  const lines = rawText.split('\n');
  let bodyHtml = '';
  let inAnswerKey = false;
  let inExplanations = false;
  let answerKeyRows: string[][] = [];

  for (let i = 0; i < lines.length; i++) {
    const line = lines[i].trim();
    if (!line) {
      bodyHtml += '<p style="margin: 4px 0;">&nbsp;</p>';
      continue;
    }

    if (line.includes('BẢNG ĐÁP ÁN TRẮC NGHIỆM TÓM TẮT') || line.includes('ANSWER KEY')) {
      inAnswerKey = true;
      inExplanations = false;
      bodyHtml += `
        <div style="page-break-before: always; margin-top: 24px; padding-top: 12px; border-top: 2px solid #2563eb;">
          <h3 style="text-align: center; color: #1e3a8a; font-size: 14pt; margin-bottom: 8px; text-transform: uppercase;">
            ${line}
          </h3>
      `;
      continue;
    }

    if (line.includes('HƯỚNG DẪN GIẢI CHI TIẾT') || line.includes('DETAILED EXPLANATIONS')) {
      if (inAnswerKey) {
        // Close table if still open
        if (answerKeyRows.length > 0) {
          bodyHtml += renderAnswerGridTable(answerKeyRows);
          answerKeyRows = [];
        }
        bodyHtml += '</div>';
        inAnswerKey = false;
      }
      inExplanations = true;
      bodyHtml += `
        <div style="margin-top: 20px;">
          <h3 style="text-align: center; color: #047857; font-size: 14pt; margin-bottom: 12px; text-transform: uppercase;">
            ${line}
          </h3>
      `;
      continue;
    }

    if (inAnswerKey) {
      if (line.startsWith('|')) {
        const cells = line.split('|').map(c => c.trim()).filter(Boolean);
        if (cells.length > 0) {
          answerKeyRows.push(cells);
        }
      }
      continue;
    }

    if (inExplanations) {
      const qMatch = line.match(/^(?:Question|Câu)\s*(\d{1,3}):\s*(.*)$/i);
      if (qMatch) {
        bodyHtml += `
          <p style="margin: 6px 0; font-size: 11pt; line-height: 1.5; text-align: justify;">
            <strong style="color: #1e40af;">Question ${qMatch[1]}:</strong> ${qMatch[2]}
          </p>
        `;
      } else {
        bodyHtml += `<p style="margin: 4px 0; font-size: 11pt; line-height: 1.5; text-align: justify;">${line}</p>`;
      }
      continue;
    }

    // Normal questions & instructions
    if (line.startsWith('SỞ GIÁO DỤC') || line.startsWith('TRƯỜNG THPT')) {
      bodyHtml += `<p style="font-weight: bold; font-size: 11pt; color: #374151; margin: 2px 0;">${line}</p>`;
    } else if (line.startsWith('KỲ THI') || line.startsWith('ĐỀ KIỂM TRA')) {
      bodyHtml += `<h2 style="font-weight: bold; font-size: 15pt; color: #1e3a8a; text-align: center; margin: 6px 0;">${line}</h2>`;
    } else if (line.startsWith('MÔN') || line.startsWith('Thời gian') || line.startsWith('Mã đề')) {
      bodyHtml += `<p style="font-style: italic; font-size: 11pt; text-align: center; margin: 2px 0; color: #4b5563;">${line}</p>`;
    } else if (line.startsWith('Read the following') || line.startsWith('Mark the letter')) {
      bodyHtml += `
        <div style="background-color: #f1f5f9; border-left: 4px solid #2563eb; padding: 8px 12px; margin: 12px 0 8px 0;">
          <p style="font-weight: bold; font-style: italic; color: #1e40af; margin: 0; font-size: 11.5pt;">${line}</p>
        </div>
      `;
    } else if (line.startsWith('Question') || line.startsWith('Câu')) {
      bodyHtml += `<p style="font-weight: bold; font-size: 12pt; color: #111827; margin: 10px 0 4px 0;">${line}</p>`;
    } else if (line.match(/^A\.\s+.*?\bB\.\s+/)) {
      // Inline options on single line
      const opts = line.split(/\s{2,}|\t/).filter(Boolean);
      bodyHtml += `
        <table style="width: 100%; border-collapse: collapse; margin: 4px 0 8px 0;">
          <tr>
            ${opts.map(opt => `<td style="width: 25%; padding: 3px 6px; font-size: 11pt; vertical-align: top;">${opt.replace(/^([A-D]\.)/, '<strong>$1</strong>')}</td>`).join('')}
          </tr>
        </table>
      `;
    } else if (line.startsWith('•') || line.match(/^[a-e]\./)) {
      bodyHtml += `<p style="margin: 3px 0 3px 18px; font-size: 11pt; line-height: 1.4;">${line}</p>`;
    } else {
      bodyHtml += `<p style="margin: 4px 0; font-size: 11pt; line-height: 1.5; text-align: justify;">${line}</p>`;
    }
  }

  if (inAnswerKey && answerKeyRows.length > 0) {
    bodyHtml += renderAnswerGridTable(answerKeyRows);
    bodyHtml += '</div>';
  } else if (inExplanations) {
    bodyHtml += '</div>';
  }

  const wordHtml = `
    <html xmlns:o="urn:schemas-microsoft-com:office:office" 
          xmlns:w="urn:schemas-microsoft-com:office:word" 
          xmlns="http://www.w3.org/TR/REC-html40">
    <head>
      <meta charset="utf-8">
      <title>${title}</title>
      <style>
        @page {
          size: A4 portrait;
          margin: 2cm;
        }
        body {
          font-family: 'Times New Roman', serif;
          font-size: 12pt;
          line-height: 1.45;
          color: #111827;
        }
        .instruction-banner {
          background-color: #f8fafc;
          border: 1px solid #cbd5e1;
          padding: 10px 14px;
          margin-bottom: 16px;
          border-radius: 6px;
        }
        table.answer-grid {
          border-collapse: collapse;
          width: 100%;
          margin: 10px 0;
          text-align: center;
        }
        table.answer-grid td {
          border: 1px solid #94a3b8;
          padding: 6px 4px;
          font-family: monospace;
          font-size: 11pt;
          font-weight: bold;
          color: #047857;
          background-color: #f8fafc;
        }
      </style>
    </head>
    <body>
      <div class="instruction-banner">
        <p style="font-weight: bold; color: #1e3a8a; margin: 0 0 4px 0;">
          📌 QUY CHUẨN SOẠN THẢO DÀNH CHO GIÁO VIÊN:
        </p>
        <p style="margin: 2px 0; font-size: 10.5pt; color: #334155;">
          • Bắt đầu mỗi câu hỏi bằng <b>Question X:</b> (hoặc <b>Câu X:</b>).
        </p>
        <p style="margin: 2px 0; font-size: 10.5pt; color: #334155;">
          • Bốn phương án <b>A.</b>, <b>B.</b>, <b>C.</b>, <b>D.</b> có thể nằm trên cùng 1 hàng hoặc xuống dòng.
        </p>
        <p style="margin: 2px 0; font-size: 10.5pt; color: #334155;">
          • Cuối đề tách riêng <b>Bảng đáp án trắc nghiệm</b> và <b>Hướng dẫn giải chi tiết</b>. Hệ thống AI Khảo thí bóc tách chính xác 100%!
        </p>
      </div>

      <hr style="border: 0; border-top: 1px solid #cbd5e1; margin-bottom: 16px;" />

      ${bodyHtml}
    </body>
    </html>
  `;

  const blob = new Blob(['\ufeff' + wordHtml], { type: 'application/msword;charset=utf-8' });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = fileName;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}

function renderAnswerGridTable(rows: string[][]): string {
  let html = '<table class="answer-grid" border="1" cellpadding="6" cellspacing="0">';
  rows.forEach(row => {
    html += '<tr>';
    row.forEach(cell => {
      html += `<td>${cell}</td>`;
    });
    html += '</tr>';
  });
  html += '</table>';
  return html;
}

